#!/usr/bin/env node
// 出所: ~/.claude/skills/org-ontology/scripts/export-ttl.mjs (org-ontology スキル)
// スキル側を直したら cp で同期する。CI から使えるようにリポジトリにも置いている。
// org.json を SKOS + SHACL の Turtle に書き出す。依存なし。
// 使い方: node export-ttl.mjs ontology/org.json > org.ttl
import { readFileSync } from 'node:fs'

const ont = JSON.parse(readFileSync(process.argv[2] ?? 'ontology/org.json', 'utf8'))
const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')
const slug = (s) => String(s).replace(/[^A-Za-z0-9_-]/g, '_')
const L = []

L.push('@prefix skos: <http://www.w3.org/2004/02/skos/core#> .')
L.push('@prefix sh:   <http://www.w3.org/ns/shacl#> .')
L.push('@prefix owl:  <http://www.w3.org/2002/07/owl#> .')
L.push('@prefix xsd:  <http://www.w3.org/2001/XMLSchema#> .')
L.push(`@prefix org:  <${ont.id}#> .`)
L.push('')
L.push(`# ${ont.id} v${ont.version} — generated by org-ontology/export-ttl.mjs`)
L.push('')

for (const [name, s] of Object.entries(ont.schemes)) {
  L.push(`org:${slug(name)} a skos:ConceptScheme ;`)
  L.push(`  skos:prefLabel "${esc(s.label ?? name)}"@ja .`)
  L.push('')
  for (const c of s.concepts) {
    const alt = (c.altLabel ?? []).map((a) => `"${esc(a)}"@ja`).join(', ')
    L.push(`org:${slug(name)}-${slug(c.id)} a skos:Concept ;`)
    L.push(`  skos:inScheme org:${slug(name)} ;`)
    L.push(`  skos:notation "${esc(c.id)}" ;`)
    L.push(`  skos:prefLabel "${esc(c.prefLabel)}"@ja ;`)
    if (alt) L.push(`  skos:altLabel ${alt} ;`)
    if (c.note) L.push(`  skos:note "${esc(c.note)}"@ja ;`)
    if (c.status === 'deprecated') L.push('  owl:deprecated true ;')
    L.push(`  org:termStatus "${esc(c.status)}" .`)
    L.push('')
  }
}

// SHACL: 列の値が語彙に含まれることを検査する形に落とす
const byClass = {}
for (const [name, s] of Object.entries(ont.schemes)) {
  for (const f of s.boundTo) {
    const [cls, prop] = f.split('.')
    ;(byClass[cls] ??= []).push({ prop, scheme: name, s })
  }
}
for (const [cls, props] of Object.entries(byClass)) {
  L.push(`org:${slug(cls)}Shape a sh:NodeShape ;`)
  L.push(`  sh:targetClass org:${slug(cls)} ;`)
  props.forEach(({ prop, scheme, s }, i) => {
    const inList = s.concepts.map((c) => `"${esc(c.id)}"`).join(' ')
    L.push('  sh:property [')
    L.push(`    sh:path org:${slug(prop)} ;`)
    L.push('    sh:datatype xsd:string ;')
    L.push(`    sh:in ( ${inList} ) ;`)
    if (!s.nullable) L.push('    sh:minCount 1 ;')
    L.push(`    sh:message "${esc(`${cls}.${prop} は ${scheme} 語彙の値であること`)}"@ja ;`)
    L.push(`  ]${i === props.length - 1 ? ' .' : ' ;'}`)
  })
  L.push('')
}

console.log(L.join('\n'))
